def split_one(P, key, tk, tj, ck, cj, ids, ysh, ov, h):
    """한 패널에서 노드 일부만 떼어 새 패널을 만든다. 장 사이를 잇는 선은 버린다 — 캡션이 대신 가리킨다."""
    S = set(ids)
    nodes = []
    for n in P["nodes"]:
        if n[0] not in S:
            continue
        x, y = ov.get(n[0], (n[1], round(n[2] + ysh, 2)))
        nodes.append((n[0], x, y) + tuple(n[3:]))
    edges = []
    for a, b, kind, lk, lj, route in P["edges"]:
        if a not in S or b not in S:
            continue
        if route and (a in ov or b in ov):
            r = []          # 옮긴 노드에 붙은 경로는 버리고 직선으로 — 좌표가 따라오지 않는다
        else:
            r = [(rx, round(ry + ysh, 2)) for rx, ry in route] if route else []
        edges.append((a, b, kind, lk, lj, r))
    return dict(key=key, height=h, title=(tk, tj), caption=(ck, cj),
                bands=[], nodes=nodes, edges=edges)


